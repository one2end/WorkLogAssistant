/** theme 只接受 'dark' / 'light'（明暗模式），其它值一律回退到 dark */
export function paletteFor(theme) {
  return PALETTES[theme === 'light' ? 'light' : 'dark'];
}

/** 取分类色；未知分类名按名称哈希稳定回退到该主题的主角色板 */
export function colorForCategory(theme, name) {
  const palette = paletteFor(theme);
  if (name && palette[name]) return palette[name];
  const fallback = FALLBACKS[theme] || FALLBACKS.dark;
  if (!name) return fallback[0];
  let hash = 0;
  for (let i = 0; i < name.length; i++) hash = (hash * 31 + name.charCodeAt(i)) % 997;
  return fallback[hash % fallback.length];
}
